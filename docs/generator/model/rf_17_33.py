def comp(frontend, web, application, engine, ports, links=None):
    """ports: dict porta → adaptador (na ordem). Gera ports, adapters, wiring e adapterStores."""
    adapters = list(dict.fromkeys(ports.values()))
    c = {"frontend": frontend, "web": web, "application": application, "engine": engine,
         "ports": list(ports), "adapters": adapters, "wiring": dict(ports),
         "adapterStores": {a: [ADAPTER_STORE[a]] for a in adapters}}
    if links:
        c["links"] = links
    return c


